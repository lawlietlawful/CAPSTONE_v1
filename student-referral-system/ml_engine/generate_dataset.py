"""
Data-generating process (DGP) for the student risk dataset.

WHY THIS FILE EXISTS
--------------------
The previous training script derived `risk_level` from a closed-form rule over
the four numeric features, and then picked `referral_reason` from a phrase list
*belonging to that label*. The text therefore predicted the label perfectly
(target leakage), so the Random Forest learned `text -> label` and ignored the
student's history entirely. A student with 8 prior referrals scored "low" if
their referral said "career advice".

THE FIX
-------
Here the label is generated from a LATENT risk score:

    latent = f(history) + f(recency) + f(concern_type) + 1.6 * incident_severity
             + gaussian_noise

and the text is generated ONLY from `incident_severity` (a hidden variable),
with heavy paraphrasing, filler and typos. Consequences:

  * Text is informative (it reveals incident_severity) but NOT sufficient —
    two students with the same wording land in different classes depending on
    their history and the noise term.
  * Numerics are informative but NOT sufficient either.
  * Gaussian noise creates genuine class overlap, so a perfect score is
    impossible. Accuracy in the 75-85% range is the honest ceiling.

NOISE_SIGMA was calibrated, not guessed: it is chosen so the noise term flips
the label (relative to the noiseless rule) for ~13% of rows. That fixes the
irreducible error — and therefore the Bayes-optimal accuracy — at roughly 87%.
A larger sigma made `moderate` unlearnable (recall 0.29); a much smaller one
would make the problem trivially separable and the model meaningless.

This is a synthetic dataset. It is not real Misamis University data, and the
DGP below is the exact, reproducible definition of what "risk" means here.
Seeded, so the CSV can be regenerated byte-for-byte.
"""

import argparse
import csv
import os

import numpy as np

SEED = 42
N_ROWS = 3000

# Std-dev of the latent noise term. See module docstring: tuned so ~13% of
# labels differ from the noiseless rule (Bayes ceiling ~87%).
NOISE_SIGMA = 0.45

# Latent-score cut points for the three risk bands.
THRESHOLD_MODERATE = 2.9
THRESHOLD_HIGH = 5.2

# Concern type encoding — must match RiskAssessmentService::encodeConcernType()
#   0 other · 1 academic · 2 behavioral · 3 emotional
#   4 family · 5 peer_conflict · 6 attendance
CONCERN_TYPES = [0, 1, 2, 3, 4, 5, 6]
CONCERN_PROBS = [0.10, 0.25, 0.15, 0.10, 0.10, 0.15, 0.15]

# How much each concern type contributes to latent risk.
CONCERN_RISK = {0: 0.0, 1: 0.6, 2: 1.2, 3: 1.3, 4: 0.7, 5: 1.1, 6: 0.9}

# P(incident_severity = 0 / 1 / 2) per concern type. Behavioural, emotional and
# peer-conflict concerns skew toward more severe incidents.
SEVERITY_PROBS = {
    0: [0.60, 0.30, 0.10],
    1: [0.50, 0.36, 0.14],
    2: [0.30, 0.40, 0.30],
    3: [0.32, 0.38, 0.30],
    4: [0.45, 0.37, 0.18],
    5: [0.33, 0.39, 0.28],
    6: [0.40, 0.40, 0.20],
}

# ── Text pools, keyed by the HIDDEN incident_severity (never by the label) ──
# Deliberately varied: different verbs, lengths, and registers, so the model
# cannot memorise 18 canned phrases the way it did before.

MILD = [
    "asked for career advice", "checking in for well-being",
    "wants to know about college applications", "requested a tutor for one subject",
    "minor misunderstanding with a classmate", "general counseling requested",
    "parent requested a routine check-in", "first time observation, nothing serious",
    "student seems fine, following up anyway", "asked about shifting courses",
    "needs help organizing their schedule", "wanted someone to talk to about stress",
    "asked for study tips before midterms", "curious about scholarship requirements",
    "brief chat about time management", "seems a little quiet lately, nothing alarming",
    "requested guidance on enrollment", "asked about joining an organization",
]

SERIOUS = [
    "frequently late to class", "sometimes disruptive during discussion",
    "struggling to submit requirements on time", "talked back to me during class",
    "missed several classes this month", "grades have been dropping steadily",
    "seems withdrawn and unfocused lately", "minor argument with a seatmate",
    "not participating in group work", "keeps using phone despite reminders",
    "family issues appear to be affecting grades", "lack of focus throughout the period",
    "incomplete requirements for two weeks now", "showing signs of emotional withdrawal",
    "occasional attendance concern worth noting", "arrived late three times this week",
    "distracted and unprepared for the quiz", "avoiding classmates during activities",
    "did not submit the last two assignments", "appears exhausted and disengaged",
]

SEVERE = [
    "punched a classmate in the face during my class",
    "has not attended class in weeks", "caught cheating multiple times",
    "constantly bullying others", "very aggressive behavior toward peers",
    "threatened another student after class", "failing all subjects this semester",
    "depressed and isolated, refuses to speak",
    "family problems causing severe distress", "repeated peer conflict escalation",
    "chronic truancy despite repeated warnings",
    "shouted at the instructor and walked out",
    "found with a weapon in their bag", "vandalized school property",
    "self-harm concerns raised by a classmate",
    "physically shoved another student in the hallway",
    "plagiarised the entire final paper",
    "has stopped attending and is unreachable",
    "verbally abusive toward a classmate",
    "multiple behavioral incidents reported this month",
]

TEXT_POOLS = {0: MILD, 1: SERIOUS, 2: SEVERE}

# Prefixes/suffixes that add noise without changing meaning.
PREFIXES = ["", "", "", "note: ", "reported that the student ", "adviser says ",
            "per my observation, ", "during my class today, "]
SUFFIXES = ["", "", "", ".", " - needs follow up", ", please advise",
            " (referred by adviser)", " today"]

# ~8% of referrals carry no usable text. The model MUST fall back on the
# numeric history for these — exactly the real-world case where a rushed
# teacher types almost nothing.
UNINFORMATIVE = [
    "", "see attached", "per adviser", "referred", "as discussed",
    "for guidance", "endorsed to guidance office", "n/a", "follow up",
]


def _typo(word: str, rng: np.random.Generator) -> str:
    """Drop or swap a character, so the vectorizer meets out-of-vocab tokens."""
    if len(word) < 4:
        return word
    i = int(rng.integers(1, len(word) - 1))
    if rng.random() < 0.5:
        return word[:i] + word[i + 1:]              # deletion
    return word[:i] + word[i + 1] + word[i] + word[i + 2:]  # transposition


def make_text(severity: int, rng: np.random.Generator) -> str:
    if rng.random() < 0.08:
        return str(rng.choice(UNINFORMATIVE))

    base = str(rng.choice(TEXT_POOLS[severity]))
    text = str(rng.choice(PREFIXES)) + base + str(rng.choice(SUFFIXES))

    # 12% of rows get a typo somewhere, producing OOV tokens.
    if rng.random() < 0.12:
        words = text.split()
        if words:
            j = int(rng.integers(0, len(words)))
            words[j] = _typo(words[j], rng)
            text = " ".join(words)

    return text.strip()


def generate(n: int = N_ROWS, seed: int = SEED):
    rng = np.random.default_rng(seed)

    previous_referrals = rng.poisson(1.5, n).clip(0, 15)
    behavioral_reports = rng.poisson(0.8, n).clip(0, 10)
    concern = rng.choice(CONCERN_TYPES, n, p=CONCERN_PROBS)

    # A student with no prior referral gets the 999 sentinel that the Laravel
    # services actually send. Previously 999 never appeared in training, so
    # every first-time referral was out-of-distribution at inference time.
    has_prior = previous_referrals > 0
    days = np.where(
        has_prior,
        rng.exponential(60, n).clip(0, 365).astype(int),
        999,
    )

    rows = []
    for i in range(n):
        severity = int(rng.choice([0, 1, 2], p=SEVERITY_PROBS[int(concern[i])]))

        # Recency matters only when there IS a prior referral.
        if not has_prior[i]:
            recency = 0.0
        elif days[i] <= 7:
            recency = 2.2
        elif days[i] <= 30:
            recency = 1.4
        elif days[i] <= 90:
            recency = 0.7
        else:
            recency = 0.0

        latent = (
            0.55 * min(int(previous_referrals[i]), 6)
            + 0.45 * min(int(behavioral_reports[i]), 5)
            + CONCERN_RISK[int(concern[i])]
            + recency
            + 1.6 * severity
            + rng.normal(0.0, NOISE_SIGMA)  # irreducible noise -> class overlap
        )

        if latent >= THRESHOLD_HIGH:
            label = "high"
        elif latent >= THRESHOLD_MODERATE:
            label = "moderate"
        else:
            label = "low"

        rows.append({
            "previous_referrals_count": int(previous_referrals[i]),
            "behavioral_reports_count": int(behavioral_reports[i]),
            "concern_type_encoded": int(concern[i]),
            "days_since_last_referral": int(days[i]),
            "referral_reason": make_text(severity, rng),
            "risk_level": label,
        })

    return rows


FIELDS = [
    "previous_referrals_count", "behavioral_reports_count",
    "concern_type_encoded", "days_since_last_referral",
    "referral_reason", "risk_level",
]


def main():
    parser = argparse.ArgumentParser(description="Generate the synthetic training dataset.")
    parser.add_argument("--rows", type=int, default=N_ROWS)
    parser.add_argument("--seed", type=int, default=SEED)
    args = parser.parse_args()

    rows = generate(args.rows, args.seed)

    out_dir = os.path.join(os.path.dirname(__file__), "data")
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "training_data.csv")

    with open(out_path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)

    counts = {}
    for r in rows:
        counts[r["risk_level"]] = counts.get(r["risk_level"], 0) + 1

    print(f"Wrote {len(rows)} rows -> {out_path}")
    print("Class balance:")
    for k in ("low", "moderate", "high"):
        c = counts.get(k, 0)
        print(f"  {k:<9} {c:>5}  ({c / len(rows) * 100:.1f}%)")


if __name__ == "__main__":
    main()
